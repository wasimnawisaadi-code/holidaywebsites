  file_path   text not null,
  doc_type    text,
  visibility  trip_doc_visibility not null default 'always',
  position    int not null default 0,
  bytes       int,
  created_at  timestamptz not null default now()
);

create index if not exists trip_documents_trip_idx on public.trip_documents (trip_id, position);

-- ---------------------------------------------------------------------------
-- Portal analytics
-- ---------------------------------------------------------------------------
--
-- Deliberately narrow. This records that a page was opened and which section
-- was looked at, so the office can tell whether a customer has actually read
-- the pickup instructions before ringing to ask where the driver is. That is a
-- real operational need and it justifies exactly this much.
--
-- What is NOT recorded, and must not be added later without a reason better
-- than curiosity: precise location, anything typed, any identifier that
-- outlives the trip. The portal shows the customer a plain notice saying the
-- office can see when they open it; a system that watches people without
-- telling them is a different thing wearing the same name.

create table if not exists public.trip_views (
  id          bigserial primary key,
  trip_id     uuid not null references public.trips (id) on delete cascade,
  created_at  timestamptz not null default now(),
  -- 'open' | 'day' | 'driver' | 'documents' | 'video' | 'document_open' | ...
  event       text not null,
  detail      text,
  device      text,
  -- Per-visit, from sessionStorage. Dies with the tab and is never joined to a
  -- name — enough to count visits, not enough to build a profile.
  session_id  text,

  constraint trip_views_event_len   check (length(event)  <= 40),
  constraint trip_views_detail_len  check (detail is null or length(detail) <= 200),
  constraint trip_views_session_len check (session_id is null or length(session_id) <= 64)
);

create index if not exists trip_views_trip_idx on public.trip_views (trip_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Audit trail
-- ---------------------------------------------------------------------------
--
-- Who changed what, when. The case this exists for: a pickup point is edited
-- from Exit 2 to Exit 3, the customer waits at the wrong exit, and the office
-- needs to know whether that edit happened before or after the customer opened
-- the page — and who made it.
--
-- Filled by trigger rather than by the application, so an admin screen added
-- later cannot forget to write to it. The triggers below cover the tables
-- where a wrong value reaches a traveller.

create table if not exists public.trip_audit (
  id          bigserial primary key,
  created_at  timestamptz not null default now(),
  table_name  text not null,
  row_id      text not null,
  trip_id     uuid,
  action      text not null,          -- insert | update | delete
  -- Only the fields that actually changed, old and new. Storing whole rows
  -- makes the history unreadable at exactly the moment someone needs to read
  -- it quickly.
  changes     jsonb not null default '{}'::jsonb,
  actor       text
);

create index if not exists trip_audit_trip_idx  on public.trip_audit (trip_id, created_at desc);
create index if not exists trip_audit_table_idx on public.trip_audit (table_name, row_id, created_at desc);

-- The acting admin's email, set per-connection by the application as
-- `set_config('app.actor', ..., true)`. Falls back to the database role, which
-- at least distinguishes a service-role write from a dashboard edit.
create or replace function public.trip_audit_actor() returns text
language sql stable as $$
  select coalesce(nullif(current_setting('app.actor', true), ''), current_user);
$$;

create or replace function public.trip_audit_capture() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  diff    jsonb := '{}'::jsonb;
  new_j   jsonb;
  old_j   jsonb;
  k       text;
  owner   uuid;
begin
  if (tg_op = 'INSERT') then
    new_j := to_jsonb(new);
    diff  := jsonb_build_object('new', new_j);
  elsif (tg_op = 'DELETE') then
    old_j := to_jsonb(old);
    diff  := jsonb_build_object('old', old_j);
  else
    new_j := to_jsonb(new);
    old_j := to_jsonb(old);
    -- Only changed keys. `updated_at` is excluded because it changes on every
    -- write and would make every entry look like a real edit.
    for k in select jsonb_object_keys(new_j) loop
      if k <> 'updated_at' and (new_j -> k) is distinct from (old_j -> k) then
        diff := diff || jsonb_build_object(k, jsonb_build_object('from', old_j -> k, 'to', new_j -> k));
      end if;
    end loop;
    -- Nothing of substance changed; do not record a row.
    if diff = '{}'::jsonb then
      return new;
    end if;
  end if;

  -- Which trip this belongs to, so the history can be shown on one screen.
  -- Each table reaches `trips` by a different route.
  begin
    if tg_table_name = 'trips' then
      owner := coalesce((new_j ->> 'id')::uuid, (old_j ->> 'id')::uuid);
    elsif tg_table_name in ('trip_days', 'trip_documents', 'trip_invoices') then
      owner := coalesce((new_j ->> 'trip_id')::uuid, (old_j ->> 'trip_id')::uuid);
    elsif tg_table_name = 'trip_steps' then
      select d.trip_id into owner from public.trip_days d
       where d.id = coalesce((new_j ->> 'trip_day_id')::uuid, (old_j ->> 'trip_day_id')::uuid);
    elsif tg_table_name = 'trip_blocks' then
      select d.trip_id into owner from public.trip_steps s
        join public.trip_days d on d.id = s.trip_day_id
       where s.id = coalesce((new_j ->> 'trip_step_id')::uuid, (old_j ->> 'trip_step_id')::uuid);
    end if;
  exception when others then
    owner := null;
  end;

  insert into public.trip_audit (table_name, row_id, trip_id, action, changes, actor)
  values (
    tg_table_name,
    coalesce(new_j ->> 'id', old_j ->> 'id', ''),
    owner,
    lower(tg_op),
    diff,
    public.trip_audit_actor()
  );

  if (tg_op = 'DELETE') then return old; end if;
  return new;
end $$;

drop trigger if exists trips_audit          on public.trips;
drop trigger if exists trip_days_audit      on public.trip_days;
drop trigger if exists trip_steps_audit     on public.trip_steps;
drop trigger if exists trip_blocks_audit    on public.trip_blocks;
drop trigger if exists trip_documents_audit on public.trip_documents;

create trigger trips_audit          after insert or update or delete on public.trips          for each row execute function public.trip_audit_capture();
create trigger trip_days_audit      after insert or update or delete on public.trip_days      for each row execute function public.trip_audit_capture();
create trigger trip_steps_audit     after insert or update or delete on public.trip_steps     for each row execute function public.trip_audit_capture();
create trigger trip_blocks_audit    after insert or update or delete on public.trip_blocks    for each row execute function public.trip_audit_capture();
create trigger trip_documents_audit after insert or update or delete on public.trip_documents for each row execute function public.trip_audit_capture();

-- Keep `trips.updated_at` honest, so the admin list can sort by real activity.
create or replace function public.trips_touch() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists trips_touch_updated on public.trips;
create trigger trips_touch_updated before update on public.trips
  for each row execute function public.trips_touch();

-- ---------------------------------------------------------------------------
-- Storage
-- ---------------------------------------------------------------------------
--
-- Both buckets are PRIVATE. The website's `media` bucket is public because it
-- holds marketing photographs meant to be seen; these hold one named
-- customer's meeting-point photograph and their hotel voucher, which are not
-- the same kind of thing at all.
--
-- The portal serves them as signed URLs minted per request in the SSR handler.
-- That costs one signing call per asset and means a link forwarded to a group
-- chat expires rather than becoming a permanent public URL.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'trip-media', 'trip-media', false,
  209715200,  -- 200MB: a 30-second phone clip of an airport exit is ~40MB
  array[
    'image/jpeg','image/png','image/webp','image/avif','image/heic',
    'video/mp4','video/quicktime','video/webm'
  ]
)
on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'trip-docs', 'trip-docs', false,
  26214400,  -- 25MB
  array['application/pdf','image/jpeg','image/png','image/webp']
)
on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- No storage policies for anon or authenticated are created, deliberately.
-- Uploads and signing both happen server-side with the service role, which
-- bypasses RLS. A leaked anon key cannot list a bucket, read a voucher, or
-- replace a driver's photograph.
drop policy if exists "trip media anon read"  on storage.objects;
drop policy if exists "trip docs anon read"   on storage.objects;

-- ---------------------------------------------------------------------------
-- Row Level Security: on everywhere, with no public policy anywhere
-- ---------------------------------------------------------------------------
--
-- RLS is enabled and then no policy is granted to anon or authenticated. The
-- effect is a default deny: PostgREST returns an empty set for a read and a
-- 401/403 for a write, whatever query is sent. The service role bypasses RLS
-- entirely, which is how the portal and admin read anything at all.

alter table public.trip_customers enable row level security;
alter table public.trips          enable row level security;
alter table public.trip_days      enable row level security;
alter table public.trip_steps     enable row level security;
alter table public.trip_blocks    enable row level security;
alter table public.trip_drivers   enable row level security;
alter table public.trip_progress  enable row level security;
alter table public.trip_documents enable row level security;
alter table public.trip_views     enable row level security;
alter table public.trip_audit     enable row level security;

-- Belt as well as braces. RLS governs row visibility; these REVOKEs remove the
-- table privilege itself, so even a policy added by accident in the dashboard
-- cannot open a read path. Any future loosening has to undo a line in this
-- file, which makes it visible in review.
revoke all on public.trip_customers from anon, authenticated;
revoke all on public.trips          from anon, authenticated;
revoke all on public.trip_days      from anon, authenticated;
revoke all on public.trip_steps     from anon, authenticated;
revoke all on public.trip_blocks    from anon, authenticated;
revoke all on public.trip_drivers   from anon, authenticated;
revoke all on public.trip_progress  from anon, authenticated;
revoke all on public.trip_documents from anon, authenticated;
revoke all on public.trip_views     from anon, authenticated;
revoke all on public.trip_audit     from anon, authenticated;

-- The admin list view, `trip_overview`, lives in 0002: it reports each trip's
-- outstanding balance, so it has to be created after the invoice tables exist.
