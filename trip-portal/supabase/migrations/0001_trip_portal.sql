-- Nawi Saadi Trip Portal — complete schema.
--
-- Runs against the SAME Supabase project as the marketing site, in the
-- Supabase SQL editor. Every table is prefixed `trip_` so nothing here can
-- collide with the website's `leads`, `events` or `media` tables. The two
-- applications share a database and share nothing else.
--
-- ---------------------------------------------------------------------------
-- THE SECURITY DECISION THAT SHAPES EVERYTHING BELOW
-- ---------------------------------------------------------------------------
--
-- A customer opens their trip with a link and no password. That is the right
-- product decision — a tourist will not create an account to find their
-- driver — but it means the link itself is the credential, and it decides how
-- every policy in this file has to work.
--
-- The tempting design is to let the browser read the trip directly with the
-- anon key, filtered by the token. Do not do this. PostgREST would happily
-- accept `?select=*` with no token filter at all, and the anon key is public by
-- definition — it ships inside the JavaScript bundle. One person reading the
-- page source would then be able to download every customer's itinerary, phone
-- number, hotel booking and passport-adjacent document in the database. That is
-- not a theoretical risk; it is the single most common way portals like this
-- leak.
--
-- So: the anon and authenticated roles are granted NOTHING on these tables.
-- Not select, not insert. Every read happens server-side in the portal's SSR
-- handler using the service role key, which never reaches the browser, after
-- that handler has looked up the token itself. The token is checked in code
-- that the customer cannot bypass, and a wrong token renders a 404.
--
-- The explicit REVOKE statements at the foot of this file are what enforce it.
-- They are also there so that a future change made in the Supabase dashboard,
-- which is how the website's `leads` policy was once quietly loosened, shows up
-- as a difference against this file.

-- ---------------------------------------------------------------------------
-- Customers
-- ---------------------------------------------------------------------------
--
-- Kept separate from the website's `leads` table on purpose. A lead is someone
-- who asked a question; this is someone who has paid and is travelling. They
-- have different lifecycles, different retention needs, and conflating them
-- means a marketing export can accidentally carry a travelling customer's
-- passport details.

create table if not exists public.trip_customers (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  full_name   text not null,
  phone       text,
  whatsapp    text,
  email       text,
  nationality text,
  -- Free-text for the office: dietary needs, mobility, who to call first.
  notes       text
);

create index if not exists trip_customers_name_idx on public.trip_customers (lower(full_name));

-- ---------------------------------------------------------------------------
-- Trips
-- ---------------------------------------------------------------------------

do $$ begin
  create type trip_state as enum ('draft', 'confirmed', 'in_progress', 'completed', 'cancelled');
exception when duplicate_object then null;
end $$;

create table if not exists public.trips (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),

  -- The human reference the office uses on the phone: NST-260928-001.
  trip_code     text not null unique,

  customer_id   uuid references public.trip_customers (id) on delete set null,

  title         text,
  destination   text not null,
  start_date    date not null,
  end_date      date not null,
  status        trip_state not null default 'draft',

  -- The credential in the URL.
  --
  -- Generated by the application with crypto.randomUUID-grade entropy, not by
  -- a sequence, and deliberately NOT the trip_code. NST-260928-001 is
  -- guessable by design — it encodes a date and a counter — so using it as the
  -- link would let anyone walk the whole customer list by incrementing the last
  -- three digits. They are two different identifiers doing two different jobs.
  tracking_token text not null unique,

  -- Draft/publish. A trip is built over several sittings and must not be
  -- half-visible to the customer in the meantime; the portal refuses to render
  -- a trip whose published_at is null.
  published_at   timestamptz,

  hero_image     text,
  pax_adults     int not null default 1,
  pax_children   int not null default 0,

  -- Shown in the portal's emergency panel. Defaults are applied by the
  -- application from the office numbers rather than hardcoded here, so a
  -- changed office line does not need a migration.
  emergency_name  text,
  emergency_phone text,

  created_by     text,

  constraint trips_dates_ordered check (end_date >= start_date),
  constraint trips_code_shape    check (length(trip_code) between 3 and 40),
  -- 32 hex characters minimum. A short token is a guessable token, and this is
  -- the only thing standing between a URL and someone's hotel voucher.
  constraint trips_token_length  check (length(tracking_token) >= 32)
);

create index if not exists trips_token_idx   on public.trips (tracking_token);
create index if not exists trips_status_idx  on public.trips (status, start_date desc);
create index if not exists trips_created_idx on public.trips (created_at desc);

-- ---------------------------------------------------------------------------
-- Days
-- ---------------------------------------------------------------------------

create table if not exists public.trip_days (
  id           uuid primary key default gen_random_uuid(),
  trip_id      uuid not null references public.trips (id) on delete cascade,
  day_number   int  not null,
  date         date,
  title        text not null,
  summary      text,
  cover_image  text,
  -- A day can be published while the next one is still being written.
  published    boolean not null default false,
  created_at   timestamptz not null default now(),

  unique (trip_id, day_number)
);

create index if not exists trip_days_trip_idx on public.trip_days (trip_id, day_number);

-- ---------------------------------------------------------------------------
-- Steps
-- ---------------------------------------------------------------------------
--
-- The structured spine of a day: "Step 1, Airport Arrival, 14:30, Terminal 3".
-- Content hangs off a step as blocks (next table). Splitting it this way is
-- what lets the office reorder a day by dragging three steps instead of
-- fourteen blocks, while still allowing any content inside each one.

create table if not exists public.trip_steps (
  id            uuid primary key default gen_random_uuid(),
  trip_day_id   uuid not null references public.trip_days (id) on delete cascade,
  step_number   int  not null,
  title         text not null,
  description   text,

  -- Clock time as text, not `time`. An itinerary says "around 14:30", "after
  -- lunch", "on arrival" — a typed time column forces the office to invent
  -- precision it does not have, and then the portal displays a false certainty
  -- the customer will hold us to.
  time_label    text,
  duration      text,

  location_name text,
  latitude      double precision,
  longitude     double precision,

  created_at    timestamptz not null default now(),

  unique (trip_day_id, step_number),
  constraint trip_steps_lat_range check (latitude  is null or latitude  between  -90 and  90),
  constraint trip_steps_lng_range check (longitude is null or longitude between -180 and 180)
);

create index if not exists trip_steps_day_idx on public.trip_steps (trip_day_id, step_number);

-- ---------------------------------------------------------------------------
-- Blocks — the page builder
-- ---------------------------------------------------------------------------
--
-- One table, one `kind`, one jsonb payload. The alternative — a column per
-- content type, or a table per content type — means a migration every time the
-- office wants a new kind of block, which defeats the entire purpose of
-- building an admin they can use without a developer.
--
-- The trade is that the payload's shape is enforced in TypeScript rather than
-- by the database. That is the correct place for it: the shapes change with the
-- UI, and a CHECK constraint on jsonb keys would have to be migrated in step
-- with every admin release.

do $$ begin
  create type trip_block_kind as enum (
    'text',        -- a paragraph
    'heading',     -- a subheading within a step
    'image',       -- one photograph, with a caption
    'gallery',     -- several photographs
    'video',       -- the meeting-point clip; the whole reason this exists
    'map',         -- an embedded location
    'driver',      -- a driver card, referencing trip_drivers
    'hotel',
    'flight',
    'ticket',      -- an attraction ticket or voucher
    'document',    -- a PDF, referencing trip_documents
    'contact',
    'notice',      -- "please be ready 10 minutes early"
    'emergency',
    'link',
    'checklist',
    'invoice'      -- embeds a published invoice; the table is in 0002
  );
exception when duplicate_object then null;
end $$;

create table if not exists public.trip_blocks (
  id            uuid primary key default gen_random_uuid(),
  trip_step_id  uuid not null references public.trip_steps (id) on delete cascade,
  position      int  not null,
  kind          trip_block_kind not null,

  -- Everything the block needs to render. Bounded, because this is written
  -- from a browser form and a jsonb column with no ceiling is an invitation.
  payload       jsonb not null default '{}'::jsonb,

  created_at    timestamptz not null default now(),

  constraint trip_blocks_payload_size check (pg_column_size(payload) <= 32768)
);

create index if not exists trip_blocks_step_idx on public.trip_blocks (trip_step_id, position);

-- ---------------------------------------------------------------------------
-- Drivers
-- ---------------------------------------------------------------------------
--
-- A row per driver, not per assignment, because the same driver works many
-- trips and re-typing their plate number for each one is how a wrong plate
-- reaches a customer standing in an airport car park.

create table if not exists public.trip_drivers (
  id           uuid primary key default gen_random_uuid(),
  created_at   timestamptz not null default now(),
  full_name    text not null,
  photo        text,
  phone        text,
  whatsapp     text,
  vehicle      text,
  plate_number text,
  languages    text,
  active       boolean not null default true
);

create index if not exists trip_drivers_active_idx on public.trip_drivers (active, lower(full_name));

-- ---------------------------------------------------------------------------
-- Live progress — the part the customer actually refreshes for
-- ---------------------------------------------------------------------------
--
-- Append-only. The current state is the most recent row, and the history is
-- the whole point: "driver arrived 14:12, customer picked up 14:31" is what
-- settles a dispute about a late transfer three weeks later. Storing only a
-- current status on `trips` would overwrite exactly the evidence worth keeping.

do $$ begin
  create type trip_progress_stage as enum (
    'booked',
    'documents_ready',
    'driver_assigned',
    'driver_on_the_way',
    'driver_arrived',
    'customer_picked_up',
    'transfer_started',
    'destination_reached',
    'checked_in',
    'activity_in_progress',
    'activity_complete',
    'departure_transfer',
    'trip_complete'
  );
exception when duplicate_object then null;
end $$;

create table if not exists public.trip_progress (
  id          bigserial primary key,
  trip_id     uuid not null references public.trips (id) on delete cascade,
  -- Optional: which day or step this progress concerns. Null means the trip
  -- as a whole, which is what a "documents ready" update is.
  trip_day_id uuid references public.trip_days (id) on delete set null,
  stage       trip_progress_stage not null,
  note        text,
  driver_id   uuid references public.trip_drivers (id) on delete set null,
  -- Whether the customer sees this entry. Some updates are internal.
  visible     boolean not null default true,
  created_at  timestamptz not null default now(),
  created_by  text
);

create index if not exists trip_progress_trip_idx on public.trip_progress (trip_id, created_at desc);

