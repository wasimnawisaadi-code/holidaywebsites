/**
 * Emits card-level copies of the catalogues.
 *
 * Attributed from the build's own source map, the entry chunk that loads on
 * every page was 857 KB, of which:
 *
 *   245 KB  src/data/catalogue.ts
 *   106 KB  src/data/inbound-tickets.ts + inbound-tours.ts
 *    61 KB  src/data/package-details-a.ts + -b.ts
 *    33 KB  src/data/countries.ts
 *
 * 446 KB of holiday itineraries, activity timetables and visa notes,
 * downloaded and parsed by every visitor of every page — including /privacy,
 * which needs none of it.
 *
 * The cause is import shape, not data size. __root.tsx, SiteHeader and
 * EnquiryBar reach into @/data/catalogue for a helper or six menu titles, so
 * the bundler has to place the whole module in the chunk every route loads.
 *
 * These generated files carry exactly the fields a card or a menu renders.
 * Detail routes keep importing the full data through an async loader, so it
 * lands in their own chunk instead.
 *
 * Regenerate with: node scripts/generate-lite-data.mjs
 */
import { writeFileSync, mkdirSync, rmSync, readdirSync } from "node:fs";
import { build } from "vite";
import { pathToFileURL } from "node:url";

mkdirSync("src/data/generated", { recursive: true });

const NL = String.fromCharCode(10);

/**
 * Loads a data module through Vite itself, so the TypeScript and the `@/` alias
 * resolve exactly the way they do in the real build rather than through a
 * second toolchain that could disagree with it.
 */
async function loadModule(entry, name) {
  const dir = ".lite-tmp-" + name;
  await build({
    configFile: false,
    logLevel: "error",
    build: {
      lib: { entry, formats: ["es"], fileName: name },
      outDir: dir,
      emptyOutDir: true,
      minify: false,
      ssr: true,
    },
  });
  const file = readdirSync(dir).find((f) => /[.](mjs|js)$/.test(f));
  if (!file) throw new Error("lib build produced nothing in " + dir);
  const mod = await import(pathToFileURL(process.cwd() + "/" + dir + "/" + file).href);
  rmSync(dir, { recursive: true, force: true });
  return mod;
}

const project = (rows, fields) =>
  rows.map((r) => {
    const out = {};
    for (const f of fields) if (r[f] !== undefined) out[f] = r[f];
    return out;
  });

const emit = (path, header, rows) =>
  writeFileSync(path, header + JSON.stringify(rows, null, 2) + ";" + NL, "utf8");

const kb = (o) => (JSON.stringify(o).length / 1024).toFixed(0);

// --- holiday packages ------------------------------------------------------
// Everything a PackageCard, the header menu or a list filter reads. Checked
// against the components rather than guessed.
const { packages } = await loadModule("src/data/catalogue.ts", "catalogue");
const packagesLite = project(packages, [
  "slug",
  "title",
  "destination",
  "country",
  "region",
  "days",
  "nights",
  "styles",
  "priceStatus",
  "priceFrom",
  "image",
  "intro",
  "featured",
  "seasonal",
  "isNew",
]);

emit(
  "src/data/generated/packages-lite.ts",
  [
    "// GENERATED by scripts/generate-lite-data.mjs — do not edit by hand.",
    "//",
    "// Card-level view of the holiday catalogue: the fields a PackageCard, the",
    "// header menu and the list filters render, and nothing else. Keeps the",
    "// itineraries, inclusions and package stories out of the chunk every route",
    "// loads. Detail pages still import @/data/catalogue.",
    "",
    'import type { PriceStatus, TravelStyle } from "../catalogue-meta";',
    "",
    "export type PackageLite = {",
    "  slug: string;",
    "  title: string;",
    "  destination: string;",
    "  country: string;",
    '  region: "International" | "UAE";',
    "  days: number;",
    "  nights: number;",
    "  styles: TravelStyle[];",
    "  priceStatus: PriceStatus;",
    "  priceFrom?: number;",
    "  image: string;",
    "  intro: string;",
    "  featured?: boolean;",
    "  seasonal?: string;",
    "  isNew?: boolean;",
    "};",
    "",
    "export const packagesLite: PackageLite[] = ",
  ].join(NL),
  packagesLite,
);

// --- inbound activities ----------------------------------------------------
// inbound-tours.ts and inbound-tickets.ts are 134KB between them, and every
// activity carries an overview, a timeline, price options, inclusions,
// exclusions, transport notes, important info, FAQs and a gallery. The
// homepage, /dubai, /uae, /deals and /activities each render a card.
const { inboundActivities } = await loadModule("src/data/inbound.ts", "inbound");
const activitiesLite = project(inboundActivities, [
  "slug",
  "title",
  "category",
  "emirate",
  "duration",
  "image",
  "badge",
  "instantConfirm",
  "fromPrice",
]);

emit(
  "src/data/generated/activities-lite.ts",
  [
    "// GENERATED by scripts/generate-lite-data.mjs — do not edit by hand.",
    "//",
    "// Card-level view of the inbound catalogue. Keeps the overviews, timelines,",
    "// price tables, FAQs and galleries out of the chunk every route loads.",
    "",
    'import type { InboundCategory, InboundEmirate } from "../inbound-types";',
    "",
    "export type ActivityLite = {",
    "  slug: string;",
    "  title: string;",
    "  category: InboundCategory;",
    "  emirate: InboundEmirate;",
    "  duration: string;",
    "  image: string;",
    '  badge?: "Must Try" | "Popular" | "Best Value" | "New";',
    "  instantConfirm?: boolean;",
    "  fromPrice?: number;",
    "};",
    "",
    "/** The price line a card prints. Mirrors inboundFrom() without the data. */",
    "export function activityFrom(a: { fromPrice?: number }): string {",
    '  return a.fromPrice ? "From AED " + a.fromPrice.toLocaleString() : "Price on Request";',
    "}",
    "",
    "export const activitiesLite: ActivityLite[] = ",
  ].join(NL),
  activitiesLite,
);

